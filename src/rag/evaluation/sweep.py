"""Experiment: how chunk size and retrieval mode change retrieval quality.

Builds one index per chunk size (each is its own collection, so nothing is overwritten), runs the
retrieval-only eval in dense and hybrid mode, and writes a comparison table to experiments/results.md.

Usage: python -m rag.evaluation.sweep [--golden eval/golden.csv] [--sizes 200 400 800]
"""

import argparse
import copy
import json
import time
from pathlib import Path

from rag import config as config_module
from rag.config import REPO_ROOT, load_config
from rag.evaluation.run import run_eval

OUT_DIR = REPO_ROOT / "experiments"


def variant(base: dict, chunk_size: int, mode: str) -> dict:
    config = copy.deepcopy(base)
    config["chunking"]["chunk_size_tokens"] = chunk_size
    config["chunking"]["chunk_overlap_tokens"] = max(20, chunk_size * 15 // 100)
    config["retrieval"]["mode"] = mode
    index_payload = {key: config[key] for key in ("corpus", "chunking", "embedding")}
    index_payload["code"] = "".join((REPO_ROOT / "src" / "rag" / n).read_text() for n in ("chunking.py", "index.py"))
    config["index_hash"] = config_module._short_hash(index_payload)
    config["config_hash"] = config_module._short_hash({"config": {k: v for k, v in config.items()
                                                                  if k not in ("config_hash", "index_hash")}})
    return config


def build_variant_index(config: dict) -> float:
    from rag import index as index_module
    started = time.perf_counter()
    original = index_module.load_config
    index_module.load_config = lambda: config
    try:
        index_module.build_index()
    finally:
        index_module.load_config = original
    return time.perf_counter() - started


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--golden", type=Path, default=REPO_ROOT / "eval" / "golden.csv")
    parser.add_argument("--sizes", type=int, nargs="+", default=[200, 400, 800])
    args = parser.parse_args()

    base = load_config()
    rows = []
    for size in args.sizes:
        build_variant_index(variant(base, size, "dense"))
        for mode in ("dense", "hybrid"):
            config = variant(base, size, mode)
            results = run_eval(args.golden, config=config, retrieval_only=True)
            overall = results["retrieval"]["overall"]
            slices = results["retrieval"]["by_slice"]
            rows.append({"chunk_size": size, "mode": mode, **overall,
                         "config_flag_recall_at_5": slices.get("config_flag", {}).get("recall_at_5")})
            print(f"chunk {size:>4} {mode:<6} recall@5={overall['recall_at_5']:.3f} mrr@10={overall['mrr_at_10']:.3f}")

    OUT_DIR.mkdir(exist_ok=True)
    (OUT_DIR / "results.json").write_text(json.dumps({"golden": args.golden.name, "rows": rows}, indent=2))
    lines = [f"# Retrieval experiment: chunk size × retrieval mode\n",
             f"Golden set: `{args.golden.name}`, answerable questions only. Generated by `make sweep`.\n",
             "| Chunk tokens | Mode | Recall@1 | Recall@5 | Recall@10 | MRR@10 | Section@5 | config_flag Recall@5 |",
             "|---|---|---|---|---|---|---|---|"]
    for row in rows:
        flag = "–" if row["config_flag_recall_at_5"] is None else f"{row['config_flag_recall_at_5']:.3f}"
        lines.append(f"| {row['chunk_size']} | {row['mode']} | {row['recall_at_1']:.3f} | {row['recall_at_5']:.3f} | "
                     f"{row['recall_at_10']:.3f} | {row['mrr_at_10']:.3f} | {row['section_at_5']:.3f} | {flag} |")
    (OUT_DIR / "results.md").write_text("\n".join(lines) + "\n")
    print(f"\nwrote {(OUT_DIR / 'results.md').relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
